#[cfg(target_pointer_width = "64")]
#[cfg_attr(
    miri,
    ignore = "the 381-limb interpolation carry fixture is covered by native execution"
)]
#[test]
fn sparse_square_propagates_interpolation_guard_carries() {
    let a: Vec<Limb> = REGRESSION_OPERAND.to_vec();
    let result_len = a.len().checked_mul(2).expect("test square fits");
    let mut expected = vec![0; result_len];
    let mut actual = vec![Limb::MAX; result_len];
    Schoolbook::sqr(&mut expected, &a);

    let scratch_len = Multiplication::toom4_sqr_scratch_len(a.len());
    let mut scratch = vec![Limb::MAX; scratch_len];
    Toom4::sqr(&mut actual, &a, &mut scratch);
    assert_eq!(actual, expected);
}
