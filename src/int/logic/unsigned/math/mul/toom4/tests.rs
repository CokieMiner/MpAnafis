fn balanced_operands() -> impl Strategy<Value = (Vec<Limb>, Vec<Limb>)> {
    prop_oneof![
        (
            proptest::collection::vec(any::<Limb>(), 4),
            proptest::collection::vec(any::<Limb>(), 4),
        ),
        (
            proptest::collection::vec(any::<Limb>(), 17),
            proptest::collection::vec(any::<Limb>(), 17),
        ),
        (
            proptest::collection::vec(any::<Limb>(), 71),
            proptest::collection::vec(any::<Limb>(), 71),
        ),
        (
            proptest::collection::vec(any::<Limb>(), 129),
            proptest::collection::vec(any::<Limb>(), 129),
        ),
        (
            proptest::collection::vec(any::<Limb>(), 257),
            proptest::collection::vec(any::<Limb>(), 257),
        ),
    ]
}

proptest! {
    #![proptest_config(ProptestConfig::with_cases(8))]

    #[test]
    fn prop_toom4_matches_basecase((a, b) in balanced_operands()) {
        let result_len = a.len().wrapping_add(b.len());
        let mut expected = vec![0; result_len];
        let mut actual = vec![Limb::MAX; result_len];
        Schoolbook::mul(&mut expected, &a, &b);

        let scratch_len = Multiplication::toom4_mul_scratch_len(a.len(), b.len());
        let mut scratch = vec![Limb::MAX; scratch_len];
        Toom4::mul(&mut actual, &a, &b, &mut scratch);
        prop_assert_eq!(actual, expected);
    }

    #[test]
    fn prop_toom4_square_matches_basecase(a in proptest::collection::vec(any::<Limb>(), 4..258)) {
        let result_len = a.len().wrapping_mul(2);
        let mut expected = vec![0; result_len];
        let mut actual = vec![Limb::MAX; result_len];
        Schoolbook::sqr(&mut expected, &a);

        let scratch_len = Multiplication::toom4_sqr_scratch_len(a.len());
        let mut scratch = vec![Limb::MAX; scratch_len];
        Toom4::sqr(&mut actual, &a, &mut scratch);
        prop_assert_eq!(actual, expected);
    }
}

