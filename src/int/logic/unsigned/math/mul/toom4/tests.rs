/// Regression: Toom-4 reconstruction dropped an interpolation guard carry.
///
/// The operand is base^3 of the CI `int_ops` crash artifact: a 381-limb square
/// in the Toom-4 dispatch range whose evaluated coefficients produced a carry
/// into a full-limb guard. Before the fix, `reconstruct_around_quadratic`
/// added that carry to the guard's first limb without propagating it, so the
/// "interpolation guard dropped a carry" assertion fired; in release the carry
/// was silently lost and the product was wrong. The square now matches schoolbook.
#[cfg(target_pointer_width = "64")]
#[test]
fn regress_toom4_guard_carry() {
    // This test is gated to 64-bit `usize`, where `Limb == u64`, so the array
    // needs no conversion: `REGRESSION_OPERAND` is already `[Limb; 381]`.
    let a: Vec<Limb> = REGRESSION_OPERAND.to_vec();
    let result_len = a.len().wrapping_mul(2);
    let mut expected = vec![0; result_len];
    let mut actual = vec![Limb::MAX; result_len];
    Schoolbook::sqr(&mut expected, &a);

    let scratch_len = Multiplication::toom4_sqr_scratch_len(a.len());
    let mut scratch = vec![Limb::MAX; scratch_len];
    Toom4::sqr(&mut actual, &a, &mut scratch);
    assert_eq!(actual, expected);
}

/// Operands in the Toom-4 squaring dispatch range `[sqr_toom_cook_4,
/// sqr_toom_cook_6)` with limbs biased toward `Limb::MAX`, so interpolation
/// carries frequently collide with full-limb coefficient guards — the failure
/// class of the reconstruction carry bug.
fn toom4_square_operands() -> impl Strategy<Value = Vec<Limb>> {
    let len = 320..398_usize;
    let limb = prop_oneof![
        3 => Just(Limb::MAX),
        7 => any::<Limb>(),
    ];
    proptest::collection::vec(limb, len).prop_map(|mut v| {
        // Keep the operand normalized so the tier shape is stable. The length
        // range starts at 320, so the operand is never empty here.
        *v.last_mut().expect("length range 320..398 is never empty") |= 1;
        v
    })
}

proptest! {
    #![proptest_config(ProptestConfig::with_cases(64))]

    #[test]
    fn prop_toom4_square_guard_range(a in toom4_square_operands()) {
        let result_len = a.len().wrapping_mul(2);
        let mut expected = vec![0; result_len];
        let mut actual = vec![Limb::MAX; result_len];
        Schoolbook::sqr(&mut expected, &a);

        let scratch_len = Multiplication::toom4_sqr_scratch_len(a.len());
        let mut scratch = vec![Limb::MAX; scratch_len];
        Toom4::sqr(&mut actual, &a, &mut scratch);
        prop_assert_eq!(actual, expected);
    }
}
